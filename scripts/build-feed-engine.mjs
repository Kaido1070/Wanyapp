import fs from 'node:fs';
import path from 'node:path';
import { stripTypeScriptTypes } from 'node:module';
const base = process.argv[2] || '../anytime';
const output = new URL('../Wany/Resources/FeedEngine.js', import.meta.url);
const read = p => fs.readFileSync(path.join(base,p),'utf8');
const strip = source => stripTypeScriptTypes(source,{mode:'transform'}).replace(/^import[\s\S]*?;\s*/gm,'').replace(/\bexport /g,'');
const wrap = (code, exports) => `(()=>{\n${strip(code)}\nreturn {${exports}};\n})()`;
const titles = read('src/data/mangatimeEnglishTitles.json');
const sourceTitles = wrap(`const mangaTimeEnglishTitles = ${titles};\n${read('src/services/sourceTitles.ts')}`,'sourceEnglishTitle');
const config = wrap(read('src/services/recommendationConfig.ts'),'RECOMMENDATION_ALGORITHM_VERSION,RECOMMENDATION_CACHE_TTL_MS,RECOMMENDATION_WEIGHTS');
const merge = wrap(read('src/services/sourceMerge.ts'),'mergeSourceItems,preferredSourceCover');
const recommendations = wrap(read('src/services/recommendations.ts'),'rankRecommendations');
const fypFull = read('src/pages/Fyp.tsx');
const fyp = fypFull.slice(fypFull.indexOf('const SOURCES:'), fypFull.indexOf('function FypProgress'));
const newFeed = read('src/services/newChapters.ts');
const discoverFull=read('src/pages/Discover.tsx');
const filterPart=discoverFull.slice(discoverFull.indexOf('type SourceFilter'),discoverFull.indexOf('async function enrich'));
const pureFilters=filterPart.slice(0,filterPart.indexOf('async function')<0 ? filterPart.length : filterPart.indexOf('async function'));
let result = `// Generated from Wany client algorithms. No WebView, DOM, or remote code execution.\n`;
result += fs.readFileSync(new URL('feed-bridge.js',import.meta.url),'utf8')+'\n';
result += `const {sourceEnglishTitle} = ${sourceTitles};\n`;
result += `const {RECOMMENDATION_ALGORITHM_VERSION,RECOMMENDATION_CACHE_TTL_MS,RECOMMENDATION_WEIGHTS} = ${config};\nconst W = RECOMMENDATION_WEIGHTS;\n`;
result += `const {mergeSourceItems,preferredSourceCover} = ${merge};\n`;
result += `const discoveryRules = ${wrap(pureFilters,'matchesMetadata,GENRES,WORK_TYPES,STATUSES')};\n`;
result += `function catalogGroups(items,filter) {return mergeSourceItems(items.filter(i=>(!filter.source || filter.source==='all' || i.source===filter.source) && discoveryRules.matchesMetadata(i,filter.genres||[],filter.type||'all',filter.status||'all'))); }\n`;
result += `const {rankRecommendations} = ${recommendations};\n`;
result += `const fypEngine = ${wrap(fyp,'buildFyp')};\n`;
result += `const newEngine = ${wrap(newFeed,'loadNewChapterFeed')};\n`;
result += `async function runFeed(kind, data, userId, page, runId) {\n try { const report = p => nativeProgress(runId, JSON.stringify(p)); const value = kind === 'fyp' ? await fypEngine.buildFyp(data,userId,report) : await newEngine.loadNewChapterFeed(page,report); nativeResult(runId,JSON.stringify(value),''); } catch(e) { nativeResult(runId,'',String(e.message || e)); }\n}\n`;
fs.writeFileSync(output,result);
const statsFull=read('src/components/ReadingStatsDashboard.tsx');
const milestones=statsFull.slice(statsFull.indexOf('const CHAPTER_TROPHIES'),statsFull.indexOf('function formatNumber'));
const milestoneCode=wrap(milestones,'CHAPTER_TROPHIES,STORY_TROPHIES,STREAK_TROPHIES');
const vm=await import('node:vm');
const options=vm.runInNewContext(result+';JSON.stringify({genres:discoveryRules.GENRES,types:discoveryRules.WORK_TYPES,statuses:discoveryRules.STATUSES})',{nativeRequest(){},nativeResult(){},nativeProgress(){},nativeTimer(){}});
fs.writeFileSync(new URL('../Wany/Resources/DiscoveryOptions.json',import.meta.url),options+'\n');
const milestoneData=vm.runInNewContext('JSON.stringify('+milestoneCode+')');
fs.writeFileSync(new URL('../Wany/Resources/ReadingMilestones.json',import.meta.url),milestoneData+'\n');
console.log(`Feed engine: ${result.length} characters`);
